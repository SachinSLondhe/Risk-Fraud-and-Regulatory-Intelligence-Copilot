INSERT INTO RAW.CUSTOMERS (CUSTOMER_ID, CUSTOMER_TYPE, RISK_RATING, KYC_STATUS,
    COUNTRY_CODE, OCCUPATION_CATEGORY, EXPECTED_MONTHLY_TURNOVER, ONBOARDING_DATE, IS_PEP)
SELECT
    'C' || LPAD(SEQ4()::VARCHAR, 6, '0') AS CUSTOMER_ID,
    CASE MOD(SEQ4(), 10)
        WHEN 0 THEN 'CORPORATE'
        WHEN 1 THEN 'NBFC_BORROWER'
        ELSE 'INDIVIDUAL'
    END AS CUSTOMER_TYPE,
    CASE
        WHEN MOD(SEQ4() * 7 + 3, 100) < 60 THEN 'LOW'
        WHEN MOD(SEQ4() * 7 + 3, 100) < 90 THEN 'MEDIUM'
        ELSE 'HIGH'
    END AS RISK_RATING,
    CASE
        WHEN MOD(SEQ4() * 13 + 5, 100) < 85 THEN 'VERIFIED'
        WHEN MOD(SEQ4() * 13 + 5, 100) < 95 THEN 'PENDING'
        ELSE 'EXPIRED'
    END AS KYC_STATUS,
    CASE MOD(SEQ4() * 11 + 2, 8)
        WHEN 0 THEN 'IND'  WHEN 1 THEN 'USA'  WHEN 2 THEN 'GBR'
        WHEN 3 THEN 'SGP'  WHEN 4 THEN 'ARE'  WHEN 5 THEN 'DEU'
        WHEN 6 THEN 'AUS'  ELSE 'CAN'
    END AS COUNTRY_CODE,
    CASE MOD(SEQ4() * 17, 8)
        WHEN 0 THEN 'SALARIED' WHEN 1 THEN 'BUSINESS' WHEN 2 THEN 'RETIRED'
        WHEN 3 THEN 'STUDENT'  WHEN 4 THEN 'PROFESSIONAL' WHEN 5 THEN 'GOVERNMENT'
        WHEN 6 THEN 'AGRICULTURE' ELSE 'OTHER'
    END AS OCCUPATION_CATEGORY,
    ROUND(CASE
        WHEN MOD(SEQ4() * 7 + 3, 100) < 60 THEN 50000 + MOD(SEQ4() * 31, 200000)
        WHEN MOD(SEQ4() * 7 + 3, 100) < 90 THEN 200000 + MOD(SEQ4() * 31, 500000)
        ELSE 500000 + MOD(SEQ4() * 31, 2000000)
    END, 2) AS EXPECTED_MONTHLY_TURNOVER,
    DATEADD('day', -MOD(SEQ4() * 23, 1800), '2026-06-01'::DATE) AS ONBOARDING_DATE,
    CASE WHEN MOD(SEQ4() * 19, 100) < 3 THEN TRUE ELSE FALSE END AS IS_PEP
FROM TABLE(GENERATOR(ROWCOUNT => 500));

