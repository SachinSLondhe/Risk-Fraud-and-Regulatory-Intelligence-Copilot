-- 5. Generate daily balances (90 days for active accounts)
-- -------------------------------------------------------
INSERT INTO RAW.ACCOUNT_DAILY_BALANCE (ACCOUNT_ID, BALANCE_DATE, OPENING_BALANCE,
    TOTAL_CREDITS, TOTAL_DEBITS, CLOSING_BALANCE, AVAILABLE_LIQUIDITY)
SELECT
    A.ACCOUNT_ID,
    D.DT AS BALANCE_DATE,
    ROUND(A.CURRENT_BALANCE + MOD(ABS(HASH(A.ACCOUNT_ID || D.DT::VARCHAR)), 100000) - 50000, 2) AS OPENING_BALANCE,
    ROUND(MOD(ABS(HASH(A.ACCOUNT_ID || D.DT::VARCHAR || 'C')), 200000), 2) AS TOTAL_CREDITS,
    ROUND(MOD(ABS(HASH(A.ACCOUNT_ID || D.DT::VARCHAR || 'D')), 180000), 2) AS TOTAL_DEBITS,
    ROUND(A.CURRENT_BALANCE + MOD(ABS(HASH(A.ACCOUNT_ID || D.DT::VARCHAR)), 100000) - 50000
        + MOD(ABS(HASH(A.ACCOUNT_ID || D.DT::VARCHAR || 'C')), 200000)
        - MOD(ABS(HASH(A.ACCOUNT_ID || D.DT::VARCHAR || 'D')), 180000), 2) AS CLOSING_BALANCE,
    ROUND(A.CURRENT_BALANCE + MOD(ABS(HASH(A.ACCOUNT_ID || D.DT::VARCHAR)), 100000) - 50000
        + MOD(ABS(HASH(A.ACCOUNT_ID || D.DT::VARCHAR || 'C')), 200000)
        - MOD(ABS(HASH(A.ACCOUNT_ID || D.DT::VARCHAR || 'D')), 180000)
        + COALESCE(A.CREDIT_LIMIT, 0), 2) AS AVAILABLE_LIQUIDITY
FROM RAW.ACCOUNTS A
CROSS JOIN (
    SELECT DATEADD('day', SEQ4(), '2026-06-01'::DATE) AS DT
    FROM TABLE(GENERATOR(ROWCOUNT => 90))
) D
WHERE A.ACCOUNT_STATUS IN ('ACTIVE', 'DORMANT');

